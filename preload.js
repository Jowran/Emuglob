const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  loadConfig: () => ipcRenderer.invoke('config:load'),
  saveConfig: (data) => ipcRenderer.invoke('config:save', data),
  pickFiles: () => ipcRenderer.invoke('dialog:files'),
  pickExe: () => ipcRenderer.invoke('dialog:exe'),
  instStatus: (id, exe) => ipcRenderer.invoke('inst:status', { id, exe }),
  instInstall: (id, exe) => ipcRenderer.invoke('inst:install', { id, exe }),
  coreList: (exe) => ipcRenderer.invoke('cores:list', exe),
  coreDelete: (exe, core) => ipcRenderer.invoke('cores:delete', { exe, core }),
  coreDownload: (exe, core) => ipcRenderer.invoke('cores:download', { exe, core }),
  onInstProgress: (cb) => ipcRenderer.on('inst:progress', (_e, p) => cb(p)),
  detectEmus: () => ipcRenderer.invoke('emus:detect'),
  emuCfgLoad: (exe) => ipcRenderer.invoke('emucfg:load', exe),
  emuCfgEncode: (exe, group, bind) => ipcRenderer.invoke('emucfg:encode', { exe, group, bind }),
  emuCfgSave: (exe, changes) => ipcRenderer.invoke('emucfg:save', { exe, changes }),
  pickCover: (id) => ipcRenderer.invoke('dialog:cover', id),
  pickWallpaper: () => ipcRenderer.invoke('dialog:wallpaper'),
  scanFolder: (extensions) => ipcRenderer.invoke('scan:folder', extensions),
  launch: (payload) => ipcRenderer.invoke('game:launch', payload),
  fullscreen: (force) => ipcRenderer.invoke('win:fullscreen', force),
  quit: () => ipcRenderer.invoke('app:quit'),
  ra: (endpoint, params, ttl) => ipcRenderer.invoke('ra:call', { endpoint, params, ttl }),
  gameMove: (r) => ipcRenderer.invoke('game:move', r),
  gameFocus: () => ipcRenderer.invoke('game:focus'),
  stopGame: () => ipcRenderer.invoke('game:stop'),
  openEmbedLog: () => ipcRenderer.invoke('embed:openlog'),
  onGameEmbedded: (cb) => ipcRenderer.on('game:embedded', (_e, d) => cb(d)),
  backupsList: () => ipcRenderer.invoke('backups:list'),
  backupsRestore: (name) => ipcRenderer.invoke('backups:restore', name),
  backupsExport: () => ipcRenderer.invoke('backups:export'),
  backupsImport: () => ipcRenderer.invoke('backups:import'),
  scanPath: (dir, extensions) => ipcRenderer.invoke('scan:path', { dir, extensions }),
  filesExist: (paths) => ipcRenderer.invoke('files:exist', paths),
  reveal: (p) => ipcRenderer.invoke('shell:reveal', p),
  gameStatus: () => ipcRenderer.invoke('game:status'),
  appInfo: () => ipcRenderer.invoke('app:info'),
  autostart: (on) => ipcRenderer.invoke('app:autostart', on),
  updatePick: () => ipcRenderer.invoke('update:pick'),
  updateApply: (src) => ipcRenderer.invoke('update:apply', src),
  updateRollback: () => ipcRenderer.invoke('update:rollback'),
  updateCheck: () => ipcRenderer.invoke('update:check'),
  updateDownload: () => ipcRenderer.invoke('update:download'),
  updatePage: () => ipcRenderer.invoke('update:page'),
  savesOpen: (id) => ipcRenderer.invoke('saves:open', id),
  savesFind: (q) => ipcRenderer.invoke('saves:find', q),
  savesImport: (items) => ipcRenderer.invoke('saves:import', items),
  savesPickDir: () => ipcRenderer.invoke('saves:pickdir'),
  discord: (on, activity, legacyId) => ipcRenderer.invoke('discord:set', { on, activity, legacyId }),
  discordStatus: () => ipcRenderer.invoke('discord:status'),
  onGameExit: (cb) => ipcRenderer.on('game:exit', (_e, d) => cb(d)),
  coresInstalled: (exe) => ipcRenderer.invoke('cores:installed', exe),
  identify: (file) => ipcRenderer.invoke('game:identify', file),
  hashGame: (file, system) => ipcRenderer.invoke('game:hash', { file, system }),
  thumbList: (folder) => ipcRenderer.invoke('thumbs:list', folder),
  downloadCover: (url, id) => ipcRenderer.invoke('cover:download', { url, id }),
});
